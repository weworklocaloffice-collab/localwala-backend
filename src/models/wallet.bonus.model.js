const mongoose = require('mongoose');
const { toJSON, paginate } = require('./plugins');

const walletBonusSchema = mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
    },
    shortDescription: {
      type: String,
      required: true,
    },
    image: {
      type: String,
      required: true,
    },
    start: {
      type: Date,
      required: true,
    },
    expires: {
      type: Date,
      required: true,
    },
    bonusType: {
      type: String,
      required: false, // amount // percentage
      default: 'amount',
    },
    bonusAmount: {
      type: Number,
      required: false,
      get: (v) => Number((v / 100).toFixed(2)),
      set: (v) => Math.round(v * 100),
      default: 0,
    },
    minWalletAmount: {
      type: Number,
      required: false,
      get: (v) => Number((v / 100).toFixed(2)),
      set: (v) => Math.round(v * 100),
      default: 0,
    },
    maxBonusAmount: {
      type: Number,
      required: false,
      get: (v) => Number((v / 100).toFixed(2)),
      set: (v) => Math.round(v * 100),
      default: 0,
    },
    translations: {
      type: Array,
      default: [],
    },
    status: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
    toJSON: { getters: true },
  }
);

// add plugin that converts mongoose to json & convert to unique slug
walletBonusSchema.plugin(toJSON);
walletBonusSchema.plugin(paginate);

/**
 * @typedef WalletBonus
 */
const WalletBonus = mongoose.model('WalletBonus', walletBonusSchema);

module.exports = WalletBonus;

