const mongoose = require('mongoose');
const { toJSON, paginate } = require('./plugins');

const deliveryGratitudeSchema = mongoose.Schema(
  {
    price: {
      type: Number,
      required: true,
      get: (v) => Number((v / 100).toFixed(2)),
      set: (v) => Math.round(v * 100),
    },
    mostTipped: {
      type: Boolean,
      default: false,
    },
    status: {
      type: Boolean,
      default: true,
    },
  },
  {
    timestamps: true,
    toJSON: { getters: true },
  }
);

// add plugin that converts mongoose to json & convert to unique slug
deliveryGratitudeSchema.plugin(toJSON);
deliveryGratitudeSchema.plugin(paginate);

/**
 * @typedef DeliveryGratitude
 */
const DeliveryGratitude = mongoose.model('DeliveryGratitude', deliveryGratitudeSchema);

module.exports = DeliveryGratitude;

