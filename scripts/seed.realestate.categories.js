/**
 * @returns {Promise<void>}
 */
const run = async () => {
  const url = process.env.MONGODB_URL || process.env.MONGODB_URI;
  if (!url) throw new Error('MONGODB_URL not set');
  await mongoose.connect(url, { serverSelectionTimeoutMS: 8000 });

  const results = { created: 0, updated: 0 };
  for (const payload of CATEGORIES) {
    const before = await categoryService.findByKey(payload.key);
    // Validate before writing so a typo in this file fails here, loudly, rather than
    // at the first property write against the broken category.
    categoryService.validateSpecSchema(payload);
    await categoryService.upsert(payload, {});
    if (before) results.updated++;
    else results.created++;
    console.log(
      `  ${before ? 'updated' : 'created'}  ${payload.key.padEnd(20)} ` +
        `${(payload.specSchema.fields || []).length} fields, ` +
        `${(payload.amenityOptions || []).length} amenities`
    );
  }

  console.log(`\n${results.created} created, ${results.updated} updated.`);
  await mongoose.disconnect();
};

run().catch(async (err) => {
  console.error('\nSEED FAILED:', err.message);
  if (err.details) console.error(err.details);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
