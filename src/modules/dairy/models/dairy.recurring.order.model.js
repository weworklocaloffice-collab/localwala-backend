const mongoose = require('mongoose');
const { toJSON, paginate } = require('../../../models/plugins');

/**
 * DairyRecurringOrder — one occurrence of a subscription.
 *
 * Generated by the nightly manifest job, then either folded into a
 * `DeliveryRun` (subscription deliveries) or fulfilled directly (one-time
 * orders). Created `planned` so an admin can see tomorrow's expected volume
 * before runs are built, and so a rerun can skip work already done.
 *
 * `clientRef` / `occurrenceDate` uniqueness is what makes the nightly job
 * idempotent: running it twice for the same date must not duplicate deliveries.
 */
const dairyRecurringOrderSchema = mongoose.Schema(
  {
    subscription: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'DairySubscription',
      required: true,
    },
    user: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'User',
      required: true,
    },
    business: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'Business',
      required: true,
    },
    sku: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'DairySku',
      required: true,
    },
    /**
     * The calendar date this occurrence delivers. Unique per subscription, which
     * is the idempotency anchor for the nightly job.
     */
    occurrenceDate: {
      type: Date,
      required: true,
    },
    quantity: {
      type: Number,
      required: true,
    },
    /**
     * Quantity and price captured at generation, not read live later — a price
     * change between generation and delivery must not silently alter the bill.
     */
    unitPrice: {
      type: Number,
      required: false,
      get: (v) => Number((v / 100).toFixed(2)),
      set: (v) => Math.round(v * 100),
      default: 0,
    },
    amount: {
      type: Number,
      required: false,
      get: (v) => Number((v / 100).toFixed(2)),
      set: (v) => Math.round(v * 100),
      default: 0,
    },
    deliverySlot: {
      startTime: {
        type: String,
        required: true,
      },
      endTime: {
        type: String,
        required: true,
      },
    },
    address: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'UserAddress',
      required: false,
    },
    addressRaw: {
      type: String,
      required: false,
    },
    /**
     * Rotation linkage when the SKU is supplied in reusable containers.
     */
    containerAssignment: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'DairyContainerAssignment',
      required: false,
    },
    /**
     * The planned bottle swap for this delivery, resolved when the occurrence was
     * generated.
     *
     * `collect` is the bottle the rider takes back, `deliver` is the one handed
     * over. Both are `null` on a first delivery, where the customer holds nothing
     * yet. Recorded here rather than looked up at delivery time so the rider's
     * manifest is a snapshot of the plan that was actually paid for, and so a
     * wash-line state change mid-route cannot silently alter it.
     */
    rotation: {
      collect: {
        type: String,
        required: false,
      },
      deliver: {
        type: String,
        required: false,
      },
      /** Deposit held for `deliver`, released when that bottle comes back. */
      depositHeld: {
        type: Number,
        required: false,
        get: (v) => Number((v / 100).toFixed(2)),
        set: (v) => Math.round(v * 100),
        default: 0,
      },
    },
    /** Set once the occurrence has been folded into a run. */
    run: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'DeliveryRun',
      required: false,
    },
    stop: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'DeliveryStop',
      required: false,
    },
    /**
     * The billable order raised for this occurrence.
     *
     * Stock is reserved and the customer is charged when the occurrence is
     * generated, so a delivery on the manifest is always something the customer
     * has already paid for and the outlet has already set aside.
     */
    order: {
      type: mongoose.SchemaTypes.ObjectId,
      ref: 'DairyOrder',
      required: false,
    },
    /**
     * Whether `quantity` units of the SKU were taken off `availableQty` for this
     * occurrence. Tracked explicitly so a failure part-way through generation can
     * return exactly what it took, and nothing more.
     */
    stockReserved: {
      type: Boolean,
      required: false,
      default: false,
    },
    status: {
      type: String,
      required: false,
      // planned -> billed -> assigned -> delivered; or skipped/cancelled when the
      // occurrence could not be prepared (no stock, or no wallet balance).
      default: 'planned',
      // planned, billed, assigned, delivered, skipped, failed, cancelled
    },
    skipReason: {
      type: String,
      required: false,
    },
  },
  {
    timestamps: true,
    toJSON: { getters: true },
  }
);

// add plugin that converts mongoose to json & convert to unique slug
dairyRecurringOrderSchema.plugin(toJSON);
dairyRecurringOrderSchema.plugin(paginate);
// The idempotency anchor for the nightly manifest job.
dairyRecurringOrderSchema.index(
  { subscription: 1, occurrenceDate: 1 },
  { unique: true }
);
dairyRecurringOrderSchema.index({ business: 1, occurrenceDate: 1, status: 1 });
dairyRecurringOrderSchema.index({ run: 1 });
dairyRecurringOrderSchema.index({ status: 1, occurrenceDate: 1 });

/**
 * @typedef DairyRecurringOrder
 */
const DairyRecurringOrder = mongoose.model(
  'DairyRecurringOrder',
  dairyRecurringOrderSchema
);

module.exports = DairyRecurringOrder;