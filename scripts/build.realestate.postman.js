/**
 * Builds the `Real Estate Routes` folder in the Postman collection from
 * the six `realestate.*.route.js` files, and injects it.
 *
 * Same contract as `build.dairy.postman.js`: method + path derived from
 * the declarations; `:params` become `{{param}}` variables with no example
 * values (a guessed ObjectId 404s and reads as a broken endpoint).
 *
 * Run with `--check` to verify the committed collection is up to date
 * without writing; CI can fail on a mismatch.
 */

const fs = require('fs');
const path = require('path');

const API_ROOT = path.join(__dirname, '..');
const COLLECTION = path.join(API_ROOT, '..', 'Resource', 'postman_collection.json');
const ROUTE_DIR = path.join(API_ROOT, 'src', 'modules', 'realestate', 'routes');

const checkOnly = process.argv.includes('--check');

const ACTORS = [
  ['public', '/v1/realestate/public', 'realestate.public.route.js'],
  ['customer', '/v1/realestate/customer', 'realestate.customer.route.js'],
  ['vendor', '/v1/realestate/vendor', 'realestate.vendor.route.js'],
  ['executive', '/v1/realestate/executive', 'realestate.executive.route.js'],
  ['bank', '/v1/realestate/bank', 'realestate.bank.route.js'],
  ['admin', '/v1/realestate/admin', 'realestate.admin.route.js'],
];

const readRoutes = (file) => {
  const src = fs.readFileSync(path.join(ROUTE_DIR, file), 'utf8');
  const re = /router\.(get|post|put|patch|delete)\(\s*'([^']+)'/g;
  const out = [];
  let m;
  while ((m = re.exec(src)) !== null) out.push({ method: m[1].toUpperCase(), path: m[2] });
  return out;
};

const toItem = (base, route) => {
  const urlPath = `{{baseUrl}}${base}${route.path.replace(/:([A-Za-z0-9_]+)/g, '{{$1}}')}`;
  const item = {
    name: `${route.method} ${route.path}`,
    request: {
      method: route.method,
      url: { raw: urlPath, host: ['{{baseUrl}}'] },
      response: [],
    },
  };
  if (route.method !== 'GET') {
    item.request.body = { mode: 'raw', raw: '{}', options: { raw: { language: 'json' } } };
  }
  return item;
};

const folders = ACTORS.map(([actor, base, file]) => ({
  name: actor,
  item: readRoutes(file).map((r) => toItem(base, r)),
})).filter((f) => f.item.length > 0);

const reFolder = {
  name: 'Real Estate Routes',
  description:
    'Generated by `scripts/build.realestate.postman.js` from `realestate.*.route.js`.\n\n' +
    'Do not hand-edit: re-run the script. Bank routes resolve the bank from the token — no bank id in any path.',
  item: folders,
};

const collection = JSON.parse(fs.readFileSync(COLLECTION, 'utf8'));
const existingIndex = (collection.item || []).findIndex((f) => f.name === 'Real Estate Routes');
if (existingIndex >= 0) collection.item.splice(existingIndex, 1, reFolder);
else collection.item.push(reFolder);

const serialised = `${JSON.stringify(collection, null, 2)}\n`;

if (checkOnly) {
  const current = fs.readFileSync(COLLECTION, 'utf8');
  if (current === serialised) {
    console.log('  up to date');
    process.exit(0);
  }
  console.error('  STALE: the committed collection differs from what the routes produce');
  process.exit(1);
}

fs.writeFileSync(COLLECTION, serialised);
const n = folders.reduce((s, f) => s + f.item.length, 0);
console.log(`  Real Estate Routes: ${n} requests in ${folders.length} folders`);
for (const f of folders) console.log(`    ${f.name.padEnd(12)} ${String(f.item.length).padStart(3)}`);
console.log(`  collection: ${COLLECTION}`);
