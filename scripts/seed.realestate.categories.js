/**
 * Seed the Real Estate property categories.
 *
 * Run:  node scripts/seed.realestate.categories.js
 *
 * ## Idempotent by design
 *
 * Keyed on `category.key`, so re-running updates the descriptors without creating
 * duplicates. That matters because these rows carry the field vocabulary — re-seeding
 * after adding a field should be the normal way to roll it out, not something that
 * needs a guard.
 *
 * ## Why `upsert` is used and not `insertMany`
 *
 * Because a category that has published properties must not lose its `specSchema` to a
 * re-seed. `upsert` merges; `insertMany` would throw on the unique `key` index.
 *
 * ## Blueprint mapping
 *
 * Blueprint §4 primary categories → `group`:
 *   Apartments, Independent Houses, Villas, Plots, Commercial
 *
 * Blueprint §4 Commercial sub-types → their own categories under `group: COMMERCIAL`:
 *   Office, Shop, Showroom, Warehouse, Commercial land
 *
 * Blueprint §7 gives the per-category field sets. Those are transcribed below as
 * descriptors — the same rows the admin form builder and the runtime validator read,
 * so there is exactly one description of "what an Apartment carries".
 */

