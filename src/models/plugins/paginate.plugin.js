const paginate = (schema) => {
  /**
   * @typedef {Object} QueryResult
   * @property {Document[]} results - Results found
   * @property {number} page - Current page
   * @property {number} limit - Maximum number of results per page
   * @property {number} totalPages - Total number of pages
   * @property {number} totalResults - Total number of documents
   */
  /**
   * Query for documents with pagination
   * @param {Object} [filter] - Mongo filter
   * @param {Object} [options] - Query options
   * @param {string} [options.sortBy] - Sorting criteria using the format: sortField:(desc|asc). Multiple sorting criteria should be separated by commas (,)
   * @param {string|Object|Array} [options.populate] - Populate data fields.
   *   Hierarchy of fields should be separated by (.). Multiple populating criteria should be separated by commas (,).
   *   Pass an object (or array of objects) such as `{ path: 'userId', select: 'firstName lastName' }`
   *   to project: without it Mongoose pulls the whole referenced document, which for a
   *   User means mobile, email and phoneHash travelling to whoever can read the list.
   * @param {number} [options.limit] - Maximum number of results per page (default = 10)
   * @param {number} [options.page] - Current page (default = 1)
   * @returns {Promise<QueryResult>}
   */
  schema.statics.paginate = async function (filter, options) {
    let sort = '';
    if (options.sortBy) {
      const sortingCriteria = [];
      options.sortBy.split(',').forEach((sortOption) => {
        const [key, order] = sortOption.split(':');
        sortingCriteria.push((order === 'desc' ? '-' : '') + key);
      });
      sort = sortingCriteria.join(' ');
    } else {
      sort = 'createdAt';
    }

    const limit =
      options.limit && parseInt(options.limit, 10) > 0 ? parseInt(options.limit, 10) : 10;
    const page = options.page && parseInt(options.page, 10) > 0 ? parseInt(options.page, 10) : 1;
    const skip = (page - 1) * limit;

    const countPromise = this.countDocuments(filter).exec();
    let docsPromise = this.find(filter).sort(sort).skip(skip).limit(limit);

    if (options.populate) {
      // Two accepted forms. A string keeps the original contract exactly: comma separated
      // paths, each optionally dotted for nesting. An object (or array of objects) is
      // Mongoose's own `populate` argument, passed straight through so a caller can ask
      // for a projection instead of an entire document.
      const populateOptions = Array.isArray(options.populate)
        ? options.populate
        : typeof options.populate === 'string'
          ? options.populate.split(',')
          : [options.populate];

      populateOptions.forEach((populateOption) => {
        if (typeof populateOption === 'string') {
          docsPromise = docsPromise.populate(
            populateOption
              .split('.')
              .reverse()
              .reduce((a, b) => ({ path: b, populate: a }))
          );
          return;
        }
        docsPromise = docsPromise.populate(populateOption);
      });
    }

    docsPromise = docsPromise.exec();

    return Promise.all([countPromise, docsPromise]).then((values) => {
      const [totalResults, results] = values;
      const totalPages = Math.ceil(totalResults / limit);
      const result = {
        results,
        page,
        limit,
        totalPages,
        totalResults,
      };
      return Promise.resolve(result);
    });
  };
};

module.exports = paginate;

